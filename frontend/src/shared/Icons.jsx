function createIcon(d, opts = {}) {
  const IconComponent = ({ size = 16, color = "currentColor", style = {}, className = "", ...props }) => (
    <svg
      width={size}
      height={size}
      viewBox="0 0 24 24"
      fill={opts.fill || "none"}
      stroke={color}
      strokeWidth={opts.strokeWidth || 2}
      strokeLinecap="round"
      strokeLinejoin="round"
      style={{ display: "inline-block", verticalAlign: "middle", flexShrink: 0, ...style }}
      className={className}
      {...props}
    >
      {typeof d === "string" ? <path d={d} /> : d}
    </svg>
  );
  return IconComponent;
}

